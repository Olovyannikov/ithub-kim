/**
 * Объявление модели как фабрики.
 *
 * Внутри фабрики живут все юниты и связи между ними, наружу отдаётся только
 * то, что перечислено в `return`. Это даёт явную публичную границу: временный
 * стор или промежуточное событие больше не утекает в страницы просто потому,
 * что кто-то дописал к нему `export`.
 *
 * ## Соглашение о возвращаемом объекте
 *
 * У модели три разных потребителя, и они разделены явно:
 *
 * | Поле        | Кто пользуется           | Что туда кладём                                   |
 * | ----------- | ------------------------ | ------------------------------------------------- |
 * | `viewModel` | компонент                | всё, что нужно разметке, и ничего сверх того       |
 * | `__`        | тесты                    | внутренности, которые нужно дёрнуть в проверке     |
 * | остальное   | другие модели            | то, чем модели связываются между собой             |
 *
 * ```ts
 * export const SomeModel = createModel(() => {
 *   const loadFx = createEffect(api.load);
 *   const $items = createStore([]).on(loadFx.doneData, (_, items) => items);
 *   const $viewState = combine($items, loadFx.pending, toListViewState);
 *
 *   return {
 *     viewModel: { $viewState },   // для компонента
 *     loadFx,                      // для других моделей
 *     __: { $items },              // для тестов
 *   };
 * });
 * ```
 *
 * Компонент при этом читается одной строкой, потому что `useUnit` принимает
 * объект:
 *
 * ```ts
 * const { $viewState: viewState } = useUnit(SomeModel.viewModel);
 * ```
 *
 * Смысл разделения прикладной: если поле нужно разметке — его видно в
 * `viewModel`, и при чтении компонента не нужно выяснять, что ещё модель
 * экспортирует. А `__` честно помечает то, что существует ради проверок:
 * такое поле нельзя трогать из страниц, и это видно по имени.
 */
interface ModelShape {
  /** Юниты для компонента. Передаётся в `useUnit` целиком. */
  viewModel?: Record<string, unknown>;
  /** Внутренности, открытые только ради тестов. */
  __?: Record<string, unknown>;
}

export const createModel = <T extends ModelShape>(factory: () => T): T => factory();
