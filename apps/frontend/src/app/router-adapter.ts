import type { RouterAdapter } from '@effector/router';

/**
 * Убирает у адаптера истории перехват нативных переходов.
 *
 * Без этого кнопка «назад» уходила в бесконечный цикл. Адаптер отдаёт роутеру
 * необязательный `block` — надстройку над `history.block` из библиотеки
 * `history`. Протокол там такой: при переходе история откатывается обратно,
 * вызывается блокировщик, и тот решает, пропустить переход через `retry()`
 * или нет. Беда в том, что подписка остаётся живой и после `retry()`, поэтому
 * переход, который `retry()` сам же и запустил, перехватывается снова:
 * `pop → go(1) → retry → go(-1) → pop → …` без конца. Снаружи это выглядело
 * так, что адрес мечется между двумя страницами, а экран не меняется вовсе.
 *
 * Блокировка переходов приложению не нужна: ни одна страница не держит
 * несохранённых данных, ради которых стоило бы останавливать пользователя.
 * Роутер обходится без неё — по его документации без `block` теряется только
 * возможность **удерживать** нативные переходы, а узнавать о них он
 * продолжает через `listen`.
 */
export function withoutNativeBlocking(adapter: RouterAdapter): RouterAdapter {
  // Наследование, а не копирование: `location` у адаптера — живое значение.
  return Object.assign(Object.create(adapter) as RouterAdapter, { block: undefined });
}
